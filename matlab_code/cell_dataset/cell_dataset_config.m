function cfg = cell_dataset_config(sampleId, outputRoot)
%CELL_DATASET_CONFIG Frozen geometry-only extension; no acquisition is run.
repoRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
if nargin < 1, sampleId = 'P06'; end
if nargin < 2 || isempty(outputRoot)
    outputRoot = fullfile(repoRoot, 'data', 'matlab_cells_pilot_v2_r04');
end
ids = {'P06','P07','P08','P09','P10','V01','V02','T01','T02'};
names = {'Neurite-like branching','Cytoskeletal bundles','120 scattered solid spheres', ...
    'Mitochondria-like short tubes','Simplified continuous 3D reticulum', ...
    'Independent line-pair validation','Independent membrane validation', ...
    'Independent point/filament test','Independent curved-network test'};
splits = {'train','train','train','validation','test', ...
    'validation','validation','test','test'};
k = find(strcmp(ids, upper(char(sampleId))));
assert(isscalar(k), 'cells:Sample', 'Unknown cell sample ID.');
cfg = struct('schema_version', 2, 'geometry_version', 'cells_geometry_v4', ...
    'dataset_id', 'matlab_cells_pilot_v2', 'sample_id', ids{k}, ...
    'description', names{k}, 'split', splits{k}, 'geometry_seed', 2026090500+k, ...
    'illumination_seed', 2027090500+k, 'subset_seed', 2028090500+k, ...
    'image_size', [260,260], 'object_pixel_pitch_um', 220/49/4, ...
    'z_um', 10:10:100, 'fine_dz_um', 1, 'fine_z_um', 5.5:1:104.5, ...
    'frame_count', 100, 'input_frames', 10, 'holdout_frames', 90, ...
    'subset_count', 10, 'iterations', 3, 'repo_root', repoRoot, ...
    'output_root', char(outputRoot), 'stage', 'truth_preview_only', ...
    'forward_status', 'not_run_requires_morphology_confirmation');
cfg.sample_dir = fullfile(outputRoot, cfg.sample_id);
cfg.x_um = (0:259)*cfg.object_pixel_pitch_um;
cfg.y_um = cfg.x_um;
if strcmp(cfg.sample_id,'P08')
    cfg.beads = struct('count',120,'radius_range_um',[5.8,7.8], ...
        'center_xy_range_um',[22,268],'center_z_range_um',[28,82], ...
        'edge_width_um',0.6,'minimum_surface_gap_um',3, ...
        'xy_clear_gap_um',2,'maximum_projected_overlap_pairs',12, ...
        'minimum_projected_radius_sum_fraction',0.85);
elseif strcmp(cfg.sample_id,'P10')
    cfg.reticulum = struct('site_count',320,'site_minimum_spacing_um',16, ...
        'collapse_edges_below_um',2.5,'midpoint_jitter_um',0.8, ...
        'tube_sigma_range_um',[0.8,1.15], ...
        'centerline_bounds_um',[32,32,22;260,260,86]);
end
end
