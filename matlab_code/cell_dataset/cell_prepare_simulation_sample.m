function prepared = cell_prepare_simulation_sample(cfg)
%CELL_PREPARE_SIMULATION_SAMPLE Freeze approved GT, split and 3D illumination.
assert(isfile(cfg.truth_path),'cells:TruthMissing','Missing truth: %s',cfg.truth_path);
truth=load(cfg.truth_path);
assert(isfield(truth,'source_sha256')&&strcmp(truth.source_sha256,cfg.truth_source_sha256), ...
    'cells:TruthChanged','Approved truth source fingerprint does not match current geometry code.');
assert(isfield(truth,'approval_status')&&isfield(truth,'ground_truth'), ...
    'cells:TruthSchema','Truth file is incomplete.');
cell_validate_truth(truth);
preparedPath=fullfile(cfg.sample_dir,'prepared.mat');
if isfile(preparedPath)
    prepared=load(preparedPath);
    assert(strcmp(prepared.cfg.dataset_id,cfg.dataset_id)&& ...
        strcmp(prepared.cfg.truth_source_sha256,cfg.truth_source_sha256)&& ...
        isequal(prepared.cfg,cfg),'cells:PreparedStale', ...
        'Existing prepared.mat belongs to another simulation protocol.');
else
    subdirs={'products','sensor_frames','recon_frames','subsets','previews','logs'};
    for index=1:numel(subdirs)
        path=fullfile(cfg.sample_dir,subdirs{index}); if ~isfolder(path), mkdir(path); end
    end
    prepared=struct('cfg',cfg,'ground_truth',truth.ground_truth, ...
        'ground_truth_fine',truth.ground_truth_fine,'truth_meta',truth.meta, ...
        'truth_metrics',truth.metrics,'truth_source_sha256',truth.source_sha256, ...
        'input_indices',truth.input_indices,'holdout_indices',truth.holdout_indices, ...
        'occupied_truth_indices_one_based',find(squeeze(sum(sum(truth.ground_truth,1),2))>0)', ...
        'protocol',{{'same propagated complex field shared by every depth', ...
        'one global YXZ legacy scale per frame; never normalize individual depth layers', ...
        'same ten frames supply both input mean and input variance', ...
        'remaining ninety frames are gradient targets, not independent test objects', ...
        'unknown-depth reconstruction always uses all ten PSF layers'}});
    pilot_atomic_save(preparedPath,prepared);
    pilot_write_tiff(fullfile(cfg.sample_dir,'previews','ground_truth_float.tif'),truth.ground_truth);
end
illuminationPath=fullfile(cfg.sample_dir,'illumination_3d.mat');
if isfile(illuminationPath)
    header=load(illuminationPath,'schema_version','dataset_id','sample_id', ...
        'truth_source_sha256','illumination_meta');
    assert(header.schema_version==cfg.schema_version&&strcmp(header.dataset_id,cfg.dataset_id)&& ...
        strcmp(header.sample_id,cfg.sample_id)&&strcmp(header.truth_source_sha256,cfg.truth_source_sha256)&& ...
        isequal(double(header.illumination_meta.z_um),double(cfg.z_um))&& ...
        header.illumination_meta.frame_count==cfg.frame_count,'cells:IlluminationStale', ...
        'Existing illumination_3d.mat is stale.');
else
    fprintf('%s: generate %d propagated 3D speckle frames\n',cfg.sample_id,cfg.frame_count);
    [illumination_raw,~,illumination_meta]=cell_generate_illumination_3d( ...
        cfg.illumination_seed,cfg.frame_count,cfg.z_um); %#ok<ASGLU>
    payload=struct('schema_version',cfg.schema_version,'dataset_id',cfg.dataset_id, ...
        'sample_id',cfg.sample_id,'truth_source_sha256',cfg.truth_source_sha256, ...
        'illumination_raw',illumination_raw,'illumination_meta',illumination_meta);
    pilot_atomic_save(illuminationPath,payload);
    clear illumination_raw payload;
end
end
