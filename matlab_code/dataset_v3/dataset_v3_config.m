function cfg = dataset_v3_config(sampleId, outputRoot)
%DATASET_V3_CONFIG Geometry-only revision; legacy generators stay frozen.
if nargin < 2, outputRoot = ''; end
repo = fileparts(fileparts(fileparts(mfilename('fullpath'))));
ids = {'T03','T04','V03'};
k = find(strcmp(ids, char(sampleId)));
assert(isscalar(k), 'v3:Sample', 'Expected T03, T04 or V03.');
names = {'Independent three-bar resolution chart', ...
    'Sparse diagonal depth-ramp 3D mesh', '60 independently scattered solid spheres'};
kinds = {'single_plane_chart','spatial_network','scattered_spheres'};
cfg = struct('schema_version',3,'dataset_id','speckle_dataset_v3', ...
    'sample_id',ids{k},'description',names{k},'geometry_kind',kinds{k}, ...
    'split','test','geometry_seed',2026090700+k, ...
    'illumination_seed',2027090700+k,'subset_seed',2028090700+k, ...
    'image_size',[260,260],'object_pixel_pitch_um',220/49/4, ...
    'z_um',10:10:100,'fine_dz_um',1,'fine_z_um',5.5:104.5, ...
    'frame_count',100,'input_frames',10,'holdout_frames',90, ...
    'subset_count',10,'iterations',3,'repo_root',repo, ...
    'output_root',char(outputRoot),'sample_dir',fullfile(outputRoot,ids{k}), ...
    'stage','truth_preview_only','morphology_approved',false, ...
    'allowed_physical_gpu_indices',0,'required_gpu_model','A40', ...
    'preview_compute','CPU_ONLY','future_gpu_policy','physical 0 A40 only; wait if busy; never share or fall back');
cfg.x_um = (0:259)*cfg.object_pixel_pitch_um;
cfg.y_um = cfg.x_um;
switch cfg.sample_id
    case 'T03'
        cfg.chart = struct('widths_px',[10,4;8,3;6,2], ...
            'pair_center_x_px',[72,192],'pair_center_y_px',[54,134,214], ...
            'pair_gap_px',12,'line_length_width_ratio',5, ...
            'line_gap_width_ratio',1,'depth_um',50,'axial_sigma_um',1, ...
            'annotation_in_truth',false);
    case 'T04'
        cfg.network = struct('station_xy_um',linspace(55,235,5), ...
            'rail_offsets_xy_um',[-22,22;0,0;22,-22], ...
            'rail_depths_um',[24,36.5,49,61.5,74;36,52.5,67,77.5,86;28,38.5,49,63.5,78], ...
            'tube_sigma_um',1.8,'amplitude',1);
    case 'V03'
        cfg.split = 'validation';
        cfg.beads = struct('count',60,'radius_range_um',[5.8,7.8], ...
            'center_xy_range_um',[22,268],'center_z_range_um',[28,82], ...
            'edge_width_um',0.6,'minimum_surface_gap_um',3, ...
            'xy_clear_gap_um',2,'maximum_projected_overlap_pairs',6, ...
            'minimum_projected_radius_sum_fraction',0.85);
end
end
