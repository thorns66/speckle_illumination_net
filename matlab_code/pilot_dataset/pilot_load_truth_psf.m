function psf = pilot_load_truth_psf(cfg)
%PILOT_LOAD_TRUTH_PSF Load only the known simulation layer for generation.
% The truth layer is used solely by the forward simulator. Reconstruction
% always loads all ten protocol depths and is never given this structure.
meta = load(cfg.psf_path, 'x3objspace', 'CAindex');
assert(all(isfield(meta, {'x3objspace','CAindex'})), 'pilot:PSFSchema', ...
    'PSF must contain x3objspace and CAindex.');
zAllUm = double(meta.x3objspace(:)) * 1e6;
hit = find(abs(zAllUm - cfg.truth_depth_um) < 1e-4);
assert(isscalar(hit), 'pilot:PSFDepth', ...
    'Truth depth %.6g um must have exactly one x3objspace match.', ...
    cfg.truth_depth_um);
m = matfile(cfg.psf_path);
hSize = size(m, 'H');
assert(numel(hSize) == 5 && hit <= hSize(5), 'pilot:PSFShape', ...
    'Truth layer is outside the five-dimensional H array.');
ca = double(meta.CAindex(hit,:));
assert(isequal(ca, [1,hSize(1)]) && hSize(1) == hSize(2), ...
    'pilot:CAIndex', 'Truth CAindex is cropped; ACC/GPU operators differ.');
truthProtocolIndex = find(abs(cfg.z_um - cfg.truth_depth_um) < 1e-4);
assert(isscalar(truthProtocolIndex), 'pilot:PSFDepth', ...
    'Truth depth is outside the ten-layer reconstruction grid.');
psf = struct('H', single(m.H(:,:,:,:,hit)), 'CAindex', ca, ...
    'truth_index_one_based', truthProtocolIndex, ...
    'source_index_one_based', hit, 'truth_depth_um', cfg.truth_depth_um, ...
    'truth_only', true);
end
