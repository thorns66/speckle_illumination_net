function cfg = pilot_dataset_config(sampleId, outputRoot)
% Frozen five-object MATLAB pilot protocol. All indices are one-based.
codeRoot = fileparts(fileparts(mfilename('fullpath')));
repoRoot = fileparts(codeRoot);
if nargin < 1, sampleId = 'P01'; end
if nargin < 2 || isempty(outputRoot)
    outputRoot = fullfile(repoRoot, 'data', 'matlab_pilot5_v1');
end
ids = {'P01','P02','P03','P04','P05'};
depths = [50,20,80,30,100];
idx = find(strcmp(ids, upper(char(sampleId))));
assert(isscalar(idx), 'pilot:Sample', 'Unknown sample ID.');
cfg = struct('schema_version', 1, 'dataset_id', 'matlab_pilot5_v1', ...
    'sample_id', ids{idx}, 'truth_depth_um', depths(idx), ...
    'image_size', [260,260], 'z_um', 10:10:100, ...
    'frame_count', 100, 'subset_count', 10, 'input_frames', 10, ...
    'holdout_frames', 90, 'iterations', 3, 'noise_model', 'none', ...
    'illumination_seed', 20260904+idx, 'subset_seed', 20261904+idx, ...
    'illumination_na', 0.05, 'illumination_wavelength_nm', 488, ...
    'illumination_pixel_pitch_um', 1.125, ...
    'object_pixel_pitch_um', 220/49/4, ...
    'code_root', codeRoot, 'repo_root', repoRoot, ...
    'output_root', char(outputRoot));
cfg.sample_dir = fullfile(outputRoot, cfg.sample_id);
cfg.psf_path = fullfile(repoRoot, 'psf', ...
    'NEW_modifyfobj_PSFmatrix_M4NA0.15MLPitch220fml4000OSR3chunk05from10to130zspacing14.6154Nnum49lambda532n1a0_-11b0_2.9333.mat');
cfg.product_path = fullfile(codeRoot, 'speckle_sample_NA0.05');
cfg.cs_reference_path = fullfile(repoRoot, 'psf', 'illumination_cs_NA0.04479.tif');
cfg.psf_depth_policy = 'match_x3objspace_not_filename_or_zspacing';
cfg.reconstruction_depth_policy = 'all_ten_layers_without_truth_depth';
cfg.legacy_sensor_policy = 'main_float_stats_then_8bit_TIFF_wrapper_input';
cfg.mean_policy = 'same_input_frames_only_no_extra_uniform';
cfg.physics_stream_note = ['P01 preserves sensor scale BEFORE sensor max normalization, ' ...
    'but its supplied 8-bit object-times-speckle already lost original illumination scale. ' ...
    'P02-P05 also retain newly generated unnormalized illumination and object products.'];
cfg.illumination_sampling_note = ['Preserve original generator 1.125 um grid; ' ...
    'existing LFM PSF object pitch is 1.1224489796 um. No silent resampling.'];
end
