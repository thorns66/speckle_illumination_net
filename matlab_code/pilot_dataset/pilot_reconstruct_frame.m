function record = pilot_reconstruct_frame(cfg, psf, frame, reconstructFcn)
%PILOT_RECONSTRUCT_FRAME Reconstruct one sensor frame by the legacy and
% retained-scale mean operators. Both outputs use all ten protocol depths.
% The legacy branch exactly mirrors TIFF round-trip input quantization:
% double in [0,1] -> uint8 -> im2double -> single.
if nargin < 4 || isempty(reconstructFcn)
    reconstructFcn = @pilot_reconstruct_volume;
end
validateattributes(frame, {'numeric'}, ...
    {'scalar','integer','>=',1,'<=',cfg.frame_count}, mfilename, 'frame');
assert(isa(reconstructFcn, 'function_handle'), 'pilot:ReconFunction', ...
    'reconstructFcn must be a function handle.');
outputPath = fullfile(cfg.sample_dir, 'recon_frames', ...
    sprintf('frame_%03d.mat', frame));
if isfile(outputPath)
    record = load(outputPath);
    validate_existing(record, cfg, psf, frame);
    return;
end

sensorPath = fullfile(cfg.sample_dir, 'sensor_frames', ...
    sprintf('frame_%03d.mat', frame));
assert(isfile(sensorPath), 'pilot:MissingSensorFrame', ...
    'Missing sensor frame: %s', sensorPath);
sensor = load(sensorPath, 'schema_version', 'dataset_id', 'sample_id', ...
    'frame_index', 'sensor_pre_detector', 'sensor_legacy_float', ...
    'sensor_legacy_uint8');
assert(isfield(sensor, 'schema_version') && ...
    sensor.schema_version == cfg.schema_version && ...
    strcmp(sensor.dataset_id, cfg.dataset_id) && ...
    strcmp(sensor.sample_id, cfg.sample_id) && sensor.frame_index == frame, ...
    'pilot:SensorFrameSchema', 'Sensor frame does not match the frozen protocol.');
validateattributes(sensor.sensor_pre_detector, {'single'}, ...
    {'real','finite','nonnegative','size',cfg.image_size}, mfilename, ...
    'sensor_pre_detector');
validateattributes(sensor.sensor_legacy_float, {'double'}, ...
    {'real','finite','nonnegative','size',cfg.image_size}, mfilename, ...
    'sensor_legacy_float');
validateattributes(sensor.sensor_legacy_uint8, {'uint8'}, ...
    {'real','size',cfg.image_size}, mfilename, 'sensor_legacy_uint8');
expectedUint8 = im2uint8(sensor.sensor_legacy_float);
assert(isequal(sensor.sensor_legacy_uint8, expectedUint8), ...
    'pilot:LegacyQuantization', ...
    'Stored legacy uint8 sensor is not the exact TIFF-equivalent encoding.');

legacyInput = single(sensor.sensor_legacy_uint8) / single(255);
physicsInput = sensor.sensor_pre_detector;
[wLegacy, legacyDiagnostic] = reconstructFcn(psf, legacyInput, ...
    cfg.iterations, 'mean');
[wPhysics, physicsDiagnostic] = reconstructFcn(psf, physicsInput, ...
    cfg.iterations, 'mean');
wLegacy = validate_volume(wLegacy, cfg, psf, 'w_legacy_raw');
wPhysics = validate_volume(wPhysics, cfg, psf, 'w_physics_raw');

record = struct('schema_version', cfg.schema_version, ...
    'dataset_id', cfg.dataset_id, 'sample_id', cfg.sample_id, ...
    'frame_index', double(frame), 'z_um', double(psf.z_um), ...
    'iterations', double(cfg.iterations), ...
    'legacy_input_uint8', sensor.sensor_legacy_uint8, ...
    'legacy_input_single', legacyInput, ...
    'physics_input_single', physicsInput, ...
    'w_legacy_raw', wLegacy, 'w_physics_raw', wPhysics, ...
    'w_legacy_preview_uint16', pilot_legacy_preview(wLegacy, 'mean'), ...
    'w_physics_preview_uint16', pilot_legacy_preview(wPhysics, 'mean'), ...
    'legacy_diagnostic', legacyDiagnostic, ...
    'physics_diagnostic', physicsDiagnostic, ...
    'legacy_input_policy', ...
        'single(im2uint8(sensor_legacy_float))/255; exact 8-bit TIFF equivalent', ...
    'physics_input_policy', ...
        'single pre-detector-normalization ACC output; no scene/frame renormalization', ...
    'raw_output_policy', ...
        'single solver output before the original display normalization');
pilot_atomic_save(outputPath, record);
end

function X = validate_volume(X, cfg, psf, name)
validateattributes(X, {'single'}, ...
    {'real','finite','nonnegative','nonsparse'}, mfilename, name);
expectedSize = [cfg.image_size, numel(cfg.z_um)];
assert(isequal(size(X), expectedSize) && numel(psf.z_um) == numel(cfg.z_um) && ...
    max(abs(double(psf.z_um(:)) - double(cfg.z_um(:)))) < 1e-9, ...
    'pilot:ReconFrameShape', '%s must be 260-by-260-by-10 at cfg.z_um.', name);
end

function validate_existing(record, cfg, psf, frame)
required = {'schema_version','dataset_id','sample_id','frame_index','z_um', ...
    'w_legacy_raw','w_physics_raw','w_legacy_preview_uint16', ...
    'w_physics_preview_uint16'};
assert(all(isfield(record, required)) && ...
    record.schema_version == cfg.schema_version && ...
    strcmp(record.dataset_id, cfg.dataset_id) && ...
    strcmp(record.sample_id, cfg.sample_id) && record.frame_index == frame && ...
    isequal(double(record.z_um(:)'), double(psf.z_um(:)')), ...
    'pilot:StaleReconstruction', ...
    'Existing frame reconstruction does not match the frozen protocol.');
validate_volume(record.w_legacy_raw, cfg, psf, 'w_legacy_raw');
validate_volume(record.w_physics_raw, cfg, psf, 'w_physics_raw');
expectedSize = [cfg.image_size, numel(cfg.z_um)];
assert(isa(record.w_legacy_preview_uint16, 'uint16') && ...
    isequal(size(record.w_legacy_preview_uint16), expectedSize) && ...
    isa(record.w_physics_preview_uint16, 'uint16') && ...
    isequal(size(record.w_physics_preview_uint16), expectedSize), ...
    'pilot:StaleReconstruction', 'Existing frame previews have invalid shape/class.');
end
