function record = pilot_build_subset(cfg, psf, subsetIndex, reconstructFcn)
%PILOT_BUILD_SUBSET Build one frozen 10-frame input / 90-frame holdout.
% Legacy statistics are computed from sensor_legacy_float BEFORE TIFF
% encoding, with sample variance var(...,0,3). Only the two reconstructed
% inputs undergo the original max normalization and uint8 TIFF-equivalent
% quantization. The retained-scale physics stream is never renormalized.
if nargin < 4 || isempty(reconstructFcn)
    reconstructFcn = @pilot_reconstruct_volume;
end
validateattributes(subsetIndex, {'numeric'}, ...
    {'scalar','integer','>=',1,'<=',cfg.subset_count}, mfilename, 'subsetIndex');
assert(isa(reconstructFcn, 'function_handle'), 'pilot:ReconFunction', ...
    'reconstructFcn must be a function handle.');
outputPath = fullfile(cfg.sample_dir, 'subsets', ...
    sprintf('subset_%02d.mat', subsetIndex));
if isfile(outputPath)
    record = load(outputPath);
    validate_existing(record, cfg, psf, subsetIndex);
    return;
end

preparedPath = fullfile(cfg.sample_dir, 'prepared.mat');
assert(isfile(preparedPath), 'pilot:MissingPrepared', ...
    'Missing frozen sample metadata: %s', preparedPath);
prepared = load(preparedPath, 'cfg', 'input_indices', 'holdout_indices');
assert(isfield(prepared, 'cfg') && ...
    strcmp(prepared.cfg.dataset_id, cfg.dataset_id) && ...
    strcmp(prepared.cfg.sample_id, cfg.sample_id) && ...
    prepared.cfg.schema_version == cfg.schema_version, 'pilot:PreparedSchema', ...
    'prepared.mat does not match the requested frozen protocol.');
inputIndices = double(prepared.input_indices(subsetIndex, :));
holdoutIndices = double(prepared.holdout_indices(subsetIndex, :));
validate_split(inputIndices, holdoutIndices, cfg);

[inputLegacyMean, inputLegacyVariance, inputPhysicsMean, inputPhysicsVariance] = ...
    compute_statistics(cfg, inputIndices);
[holdoutLegacyMean, holdoutLegacyVariance, holdoutPhysicsMean, ...
    holdoutPhysicsVariance] = compute_statistics(cfg, holdoutIndices);

[legacyMeanNormalized, legacyMeanUint8, legacyMeanPeak] = ...
    legacy_encode(inputLegacyMean, 'legacy mean');
[legacyVarianceNormalized, legacyVarianceUint8, legacyVariancePeak] = ...
    legacy_encode(inputLegacyVariance, 'legacy variance');
legacyMeanInput = single(legacyMeanUint8) / single(255);
legacyTaylorInput = single(legacyVarianceUint8) / single(255);
physicsMeanInput = single(inputPhysicsMean);
physicsTaylorInput = single(inputPhysicsVariance);

[legacyMeanRaw, legacyMeanDiagnostic] = reconstructFcn(psf, legacyMeanInput, ...
    cfg.iterations, 'mean');
[legacyTaylorRaw, legacyTaylorDiagnostic] = reconstructFcn(psf, ...
    legacyTaylorInput, cfg.iterations, 'taylor');
[physicsMeanRaw, physicsMeanDiagnostic] = reconstructFcn(psf, physicsMeanInput, ...
    cfg.iterations, 'mean');
[physicsTaylorRaw, physicsTaylorDiagnostic] = reconstructFcn(psf, ...
    physicsTaylorInput, cfg.iterations, 'taylor');
legacyMeanRaw = validate_volume(legacyMeanRaw, cfg, psf, 'legacy_mean_raw');
legacyTaylorRaw = validate_volume(legacyTaylorRaw, cfg, psf, 'legacy_taylor_raw');
physicsMeanRaw = validate_volume(physicsMeanRaw, cfg, psf, 'physics_mean_raw');
physicsTaylorRaw = validate_volume(physicsTaylorRaw, cfg, psf, 'physics_taylor_raw');

% These are intentionally distinct products. sqrt(single raw solver output)
% is the floating-point amplitude estimate; pilot_legacy_preview first
% quantizes the solver output to the historical 0.66-range uint16 volume.
legacyTaylorSqrtFloat = sqrt(legacyTaylorRaw);
physicsTaylorSqrtFloat = sqrt(physicsTaylorRaw);
legacyMeanPreview = pilot_legacy_preview(legacyMeanRaw, 'mean');
legacyTaylorPreview = pilot_legacy_preview(legacyTaylorRaw, 'taylor');
physicsMeanPreview = pilot_legacy_preview(physicsMeanRaw, 'mean');
physicsTaylorPreview = pilot_legacy_preview(physicsTaylorRaw, 'taylor');

previewDir = fullfile(cfg.sample_dir, 'previews');
previewPaths = struct( ...
    'legacy_mean', fullfile(previewDir, sprintf('subset_%02d_legacy_mean.tif', subsetIndex)), ...
    'legacy_taylor', fullfile(previewDir, sprintf('subset_%02d_legacy_taylor_sqrt.tif', subsetIndex)), ...
    'physics_mean', fullfile(previewDir, sprintf('subset_%02d_physics_mean.tif', subsetIndex)), ...
    'physics_taylor', fullfile(previewDir, sprintf('subset_%02d_physics_taylor_sqrt.tif', subsetIndex)));
pilot_write_tiff(previewPaths.legacy_mean, legacyMeanPreview);
pilot_write_tiff(previewPaths.legacy_taylor, legacyTaylorPreview);
pilot_write_tiff(previewPaths.physics_mean, physicsMeanPreview);
pilot_write_tiff(previewPaths.physics_taylor, physicsTaylorPreview);

record = struct('schema_version', cfg.schema_version, ...
    'dataset_id', cfg.dataset_id, 'sample_id', cfg.sample_id, ...
    'subset_index', double(subsetIndex), 'input_indices', inputIndices, ...
    'holdout_indices', holdoutIndices, 'z_um', double(psf.z_um), ...
    'iterations', double(cfg.iterations), ...
    'legacy_variance_normalization', 'N-1: var(sensor_legacy_float,0,3)', ...
    'physics_variance_normalization', 'N-1: var(sensor_pre_detector,0,3)', ...
    'statistics_accumulator_class', 'double', ...
    'legacy_statistics_stage', ...
        'after per-frame sensor max normalization and before TIFF quantization', ...
    'input_legacy_mean_float', inputLegacyMean, ...
    'input_legacy_variance_nminus1_float', inputLegacyVariance, ...
    'holdout_legacy_mean_float', holdoutLegacyMean, ...
    'holdout_legacy_variance_nminus1_float', holdoutLegacyVariance, ...
    'input_physics_mean_float', inputPhysicsMean, ...
    'input_physics_variance_nminus1_float', inputPhysicsVariance, ...
    'holdout_physics_mean_float', holdoutPhysicsMean, ...
    'holdout_physics_variance_nminus1_float', holdoutPhysicsVariance, ...
    'legacy_mean_normalized_float', legacyMeanNormalized, ...
    'legacy_variance_normalized_float', legacyVarianceNormalized, ...
    'legacy_mean_uint8', legacyMeanUint8, ...
    'legacy_variance_uint8', legacyVarianceUint8, ...
    'legacy_mean_input_single', legacyMeanInput, ...
    'legacy_taylor_input_single', legacyTaylorInput, ...
    'physics_mean_input_single', physicsMeanInput, ...
    'physics_taylor_input_single', physicsTaylorInput, ...
    'legacy_mean_input_peak', legacyMeanPeak, ...
    'legacy_variance_input_peak', legacyVariancePeak, ...
    'legacy_mean_raw', legacyMeanRaw, ...
    'legacy_taylor_raw', legacyTaylorRaw, ...
    'physics_mean_raw', physicsMeanRaw, ...
    'physics_taylor_raw', physicsTaylorRaw, ...
    'legacy_taylor_sqrt_float', legacyTaylorSqrtFloat, ...
    'physics_taylor_sqrt_float', physicsTaylorSqrtFloat, ...
    'legacy_mean_preview_uint16', legacyMeanPreview, ...
    'legacy_taylor_preview_uint16', legacyTaylorPreview, ...
    'physics_mean_preview_uint16', physicsMeanPreview, ...
    'physics_taylor_preview_uint16', physicsTaylorPreview, ...
    'preview_paths', previewPaths, ...
    'legacy_mean_diagnostic', legacyMeanDiagnostic, ...
    'legacy_taylor_diagnostic', legacyTaylorDiagnostic, ...
    'physics_mean_diagnostic', physicsMeanDiagnostic, ...
    'physics_taylor_diagnostic', physicsTaylorDiagnostic, ...
    'legacy_input_policy', ...
        'mean/var from float frames; max normalize; im2uint8; single/255', ...
    'physics_input_policy', ...
        'mean/var of retained-scale single frames accumulated in double; no normalization', ...
    'taylor_output_policy', ...
        'raw is solver estimate; sqrt_float and strict uint16 preview are separate');
pilot_atomic_save(outputPath, record);
end

function [legacyMean, legacyVariance, physicsMean, physicsVariance] = ...
        compute_statistics(cfg, indices)
frameCount = numel(indices);
assert(frameCount >= 2, 'pilot:StatisticsFrames', ...
    'Sample variance with N-1 normalization requires at least two frames.');
legacy = zeros(cfg.image_size(1), cfg.image_size(2), frameCount, 'double');
physics = zeros(cfg.image_size(1), cfg.image_size(2), frameCount, 'double');
for position = 1:frameCount
    frame = indices(position);
    path = fullfile(cfg.sample_dir, 'sensor_frames', sprintf('frame_%03d.mat', frame));
    assert(isfile(path), 'pilot:MissingSensorFrame', 'Missing sensor frame: %s', path);
    data = load(path, 'schema_version', 'dataset_id', 'sample_id', ...
        'frame_index', 'sensor_legacy_float', 'sensor_pre_detector');
    assert(all(isfield(data, {'schema_version','dataset_id','sample_id', ...
        'frame_index','sensor_legacy_float','sensor_pre_detector'})) && ...
        data.schema_version == cfg.schema_version && ...
        strcmp(data.dataset_id, cfg.dataset_id) && ...
        strcmp(data.sample_id, cfg.sample_id) && data.frame_index == frame, ...
        'pilot:SensorFrameSchema', 'Invalid sensor frame metadata in %s.', path);
    validateattributes(data.sensor_legacy_float, {'double'}, ...
        {'real','finite','nonnegative','size',cfg.image_size}, mfilename, ...
        'sensor_legacy_float');
    validateattributes(data.sensor_pre_detector, {'single'}, ...
        {'real','finite','nonnegative','size',cfg.image_size}, mfilename, ...
        'sensor_pre_detector');
    legacy(:,:,position) = data.sensor_legacy_float;
    physics(:,:,position) = double(data.sensor_pre_detector);
end
legacyMean = mean(legacy, 3);
legacyVariance = var(legacy, 0, 3); % explicit N-1 normalization
physicsMean = mean(physics, 3);
physicsVariance = var(physics, 0, 3); % explicit N-1 normalization
end

function [normalized, encoded, peak] = legacy_encode(image, label)
validateattributes(image, {'double'}, ...
    {'real','finite','nonnegative','2d','nonsparse'}, mfilename, label);
peak = max(image(:));
assert(peak > 0, 'pilot:EmptyStatistic', '%s is identically zero.', label);
normalized = image / peak;
encoded = im2uint8(normalized);
end

function validate_split(inputIndices, holdoutIndices, cfg)
assert(numel(inputIndices) == cfg.input_frames && ...
    numel(holdoutIndices) == cfg.holdout_frames && ...
    all(inputIndices == floor(inputIndices)) && ...
    all(holdoutIndices == floor(holdoutIndices)) && ...
    isempty(intersect(inputIndices, holdoutIndices)) && ...
    isequal(sort([inputIndices, holdoutIndices]), 1:cfg.frame_count), ...
    'pilot:Split', 'Subset must be an exact disjoint 10/90 partition of 1:100.');
end

function X = validate_volume(X, cfg, psf, name)
validateattributes(X, {'single'}, ...
    {'real','finite','nonnegative','nonsparse'}, mfilename, name);
expectedSize = [cfg.image_size, numel(cfg.z_um)];
assert(isequal(size(X), expectedSize) && numel(psf.z_um) == numel(cfg.z_um) && ...
    max(abs(double(psf.z_um(:)) - double(cfg.z_um(:)))) < 1e-9, ...
    'pilot:SubsetReconShape', '%s must be 260-by-260-by-10 at cfg.z_um.', name);
end

function validate_existing(record, cfg, psf, subsetIndex)
required = {'schema_version','dataset_id','sample_id','subset_index', ...
    'input_indices','holdout_indices','z_um','legacy_mean_raw', ...
    'legacy_taylor_raw','physics_mean_raw','physics_taylor_raw', ...
    'legacy_mean_preview_uint16','legacy_taylor_preview_uint16', ...
    'physics_mean_preview_uint16','physics_taylor_preview_uint16', ...
    'preview_paths'};
assert(all(isfield(record, required)) && ...
    record.schema_version == cfg.schema_version && ...
    strcmp(record.dataset_id, cfg.dataset_id) && ...
    strcmp(record.sample_id, cfg.sample_id) && ...
    record.subset_index == subsetIndex && ...
    isequal(double(record.z_um(:)'), double(psf.z_um(:)')), ...
    'pilot:StaleSubset', ...
    'Existing subset does not match the frozen protocol.');
validate_split(double(record.input_indices), double(record.holdout_indices), cfg);
rawNames = {'legacy_mean_raw','legacy_taylor_raw', ...
    'physics_mean_raw','physics_taylor_raw'};
for index = 1:numel(rawNames)
    validate_volume(record.(rawNames{index}), cfg, psf, rawNames{index});
end
previewNames = {'legacy_mean_preview_uint16','legacy_taylor_preview_uint16', ...
    'physics_mean_preview_uint16','physics_taylor_preview_uint16'};
expectedSize = [cfg.image_size, numel(cfg.z_um)];
for index = 1:numel(previewNames)
    preview = record.(previewNames{index});
    assert(isa(preview, 'uint16') && isequal(size(preview), expectedSize), ...
        'pilot:StaleSubset', 'Existing preview has invalid shape/class.');
end
paths = struct2cell(record.preview_paths);
assert(all(cellfun(@isfile, paths)), 'pilot:StaleSubset', ...
    'Existing subset is missing one or more published previews.');
end
