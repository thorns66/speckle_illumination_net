function [X, info] = pilot_sanitize_roundoff(X, label)
%PILOT_SANITIZE_ROUNDOFF Remove only numerically negligible negative residues.
% The frozen operator accumulates 49*49*10 single-precision convolution
% terms per volume projection/backprojection. Its first-order accumulation
% bound is gamma_n ~= n*u/(1-n*u) = 1.43e-3, so the peak-relative gate is
% conservatively rounded to 2e-3. Cleanup additionally requires negligible
% total negative mass. The mass limit is below half one uint16 level
% (0.5/65535 = 7.63e-6); either failed gate remains a hard error.
if nargin < 2 || isempty(label), label = 'reconstruction'; end
validateattributes(X, {'single'}, ...
    {'real','finite','nonempty','nonsparse'}, mfilename, 'X');
label = char(label);

minimumBefore = double(min(X(:)));
maximumAbsolute = double(max(abs(X(:))));
ulpTolerance = 8 * double(eps(single(maximumAbsolute)));
relativePeakTolerance = 2.0e-3;
negativeMassTolerance = 2.0e-6;
tolerance = max(ulpTolerance, relativePeakTolerance * maximumAbsolute);
negativeMask = X < 0;
negativeCount = double(sum(negativeMask(:)));
negativeAbsSum = double(sum(abs(X(negativeMask)), 'double'));
positiveSum = double(sum(X(X > 0), 'double'));
if maximumAbsolute > 0
    minimumRelativeToPeak = abs(min(minimumBefore, 0)) / maximumAbsolute;
else
    minimumRelativeToPeak = 0;
end
if positiveSum > 0
    negativeMassRatio = negativeAbsSum / positiveSum;
elseif negativeAbsSum == 0
    negativeMassRatio = 0;
else
    negativeMassRatio = Inf;
end

assert(minimumBefore >= -tolerance && negativeMassRatio <= negativeMassTolerance, ...
    'pilot:MaterialNegativeReconstruction', ...
    ['%s contains material negative content: min=%g, peak=%g, ' ...
     'min/peak=%g (limit=%g), negative/positive mass=%g (limit=%g), ' ...
     '8-ULP floor=%g.'], label, minimumBefore, maximumAbsolute, ...
     minimumRelativeToPeak, relativePeakTolerance, negativeMassRatio, ...
     negativeMassTolerance, ulpTolerance);
if negativeCount > 0
    X(negativeMask) = single(0);
end
info = struct( ...
    'minimum_before_roundoff_cleanup', minimumBefore, ...
    'maximum_absolute_before_roundoff_cleanup', maximumAbsolute, ...
    'negative_count_before_roundoff_cleanup', negativeCount, ...
    'negative_abs_sum_before_roundoff_cleanup', negativeAbsSum, ...
    'positive_sum_before_roundoff_cleanup', positiveSum, ...
    'negative_to_positive_mass_ratio', negativeMassRatio, ...
    'minimum_relative_to_peak', minimumRelativeToPeak, ...
    'roundoff_tolerance_abs', tolerance, ...
    'roundoff_ulp_floor_abs', ulpTolerance, ...
    'roundoff_relative_peak_limit', relativePeakTolerance, ...
    'roundoff_negative_mass_ratio_limit', negativeMassTolerance, ...
    'roundoff_accumulation_terms', 24010, ...
    'roundoff_accumulation_gamma_bound', 1.433e-3, ...
    'roundoff_tolerance_policy', ...
        'min/peak <= 2e-3 AND negative/positive mass <= 2e-6; below half one uint16 level and bounded by 24010-term float32 accumulation', ...
    'roundoff_clipped_count', negativeCount);
end
