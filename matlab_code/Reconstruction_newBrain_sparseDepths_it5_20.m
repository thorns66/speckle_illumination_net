%% ========================================================================
% 保存 txt 日志
%% ========================================================================
function writeLogTxt( ...
    logCell, ...
    filePath ...
)

fid = fopen( ...
    filePath, ...
    'w' ...
);

if fid < 0

    warning( ...
        '无法创建日志：%s', ...
        filePath ...
    );

    return;
end

cleanupObj = onCleanup( ...
    @() fclose(fid) ...
); %#ok<NASGU>

for i = 1:size(logCell, 1)

    rowText = strings( ...
        1, ...
        size(logCell, 2) ...
    );

    for j = 1:size(logCell, 2)

        currentValue = ...
            logCell{i, j};

        if isempty(currentValue)

            rowText(j) = "";

        else

            rowText(j) = ...
                string(currentValue);
        end
    end

    fprintf( ...
        fid, ...
        '%s\n', ...
        strjoin( ...
            rowText, ...
            sprintf('\t') ...
        ) ...
    );
end

