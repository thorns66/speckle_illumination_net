%% ========================================================================
% 按连续索引段读取 PSF
%% ========================================================================
function A = readPSFByContinuousRuns( ...
    M, ...
    varName, ...
    depthIdxUse ...
)

depthIdxUse = depthIdxUse(:)';

runCell = ...
    splitContinuousRuns(depthIdxUse);

A = [];

for r = 1:length(runCell)

    idxRun = runCell{r};

    fprintf( ...
        '  读取 %s：%d 到 %d，共 %d 层\n', ...
        varName, ...
        idxRun(1), ...
        idxRun(end), ...
        length(idxRun) ...
    );

    switch varName

        case 'H'

            temp = M.H( ...
                :, ...
                :, ...
                :, ...
                :, ...
                idxRun(1):idxRun(end) ...
            );

        case 'Ht'

            temp = M.Ht( ...
                :, ...
                :, ...
                :, ...
                :, ...
                idxRun(1):idxRun(end) ...
            );

        otherwise

            error( ...
                '未知 PSF 变量：%s', ...
                varName ...
            );
    end

    if ~isa(temp, 'single')
        temp = single(temp);
    end

    if isempty(A)

        A = temp;

    else

        A = cat( ...
            5, ...
            A, ...
            temp ...
        );
    end

    clear temp;
end

end


%% ========================================================================
% 把索引拆分成连续段
%% ========================================================================
function runCell = splitContinuousRuns(idx)

idx = idx(:)';

if isempty(idx)

    runCell = {};
    return;
end

breakPos = find(diff(idx) ~= 1);

startPos = [
    1, ...
    breakPos + 1 ...
];

endPos = [
    breakPos, ...
    length(idx) ...
];

runCell = cell( ...
    length(startPos), ...
    1 ...
);

for i = 1:length(startPos)

    runCell{i} = ...
        idx(startPos(i):endPos(i));
end

end


%% ========================================================================
% 获取图像列表
%% ========================================================================
function imgList = getImageList(folderPath)

imgList = [];

if ~exist(folderPath, 'dir')
    return;
end

imgList = [
    dir(fullfile(folderPath, '*.tif'));
    dir(fullfile(folderPath, '*.tiff'));
    dir(fullfile(folderPath, '*.bmp'));
    dir(fullfile(folderPath, '*.png'))
];

if isempty(imgList)
    return;
end

%% ------------------------- 去重 -----------------------------------------

fullNames = cell( ...
    length(imgList), ...
    1 ...
);

for i = 1:length(imgList)

    fullNames{i} = fullfile( ...
        imgList(i).folder, ...
        imgList(i).name ...
    );
end

[~, uniqueIdx] = unique( ...
    lower(string(fullNames)), ...
    'stable' ...
);

imgList = imgList(uniqueIdx);

%% ------------------------- 排序 -----------------------------------------

names = {imgList.name};

numbers = nan( ...
    length(names), ...
    1 ...
);

for k = 1:length(names)

    tokens = regexp( ...
        names{k}, ...
        '\d+', ...
        'match' ...
    );

    if ~isempty(tokens)

        numbers(k) = ...
            str2double(tokens{end});
    end
end

if all(~isnan(numbers))

    [~, sortIdx] = ...
        sort(numbers);

else

    [~, sortIdx] = sort( ...
        lower(string(names)) ...
    );
end

imgList = imgList(sortIdx);

end


