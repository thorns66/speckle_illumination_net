                            saveFramePath ...
                        ), ...
                        iterNum, ...
                        physicalDepth, ...
                        physicalDepth ...
                    );

                    singleSuccessNum = ...
                        singleSuccessNum + 1;

                catch ME

                    singleFailedNum = ...
                        singleFailedNum + 1;

                    taskMessages{end + 1} = sprintf( ...
                        'volume %d failed: %s', ...
                        frameLoop, ...
                        ME.message ...
                    );

                    fprintf(2, ...
                        '体积 %d 当前深度重建失败：%s\n', ...
                        frameLoop, ...
                        ME.message ...
                    );

                    errorFilePath = fullfile( ...
                        saveFramePath, ...
                        'RECONSTRUCTION_FAILED.txt' ...
                    );

                    errorText = sprintf( ...
                        ['数据集：%s\n', ...
                         '35层序号：%d\n', ...
