                            'hyperlinks', ...
                            'off' ...
                        ) ...
                    );

                    writeTextFile( ...
                        errorFilePath, ...
                        errorText ...
                    );
                end
            end
        end

        %% ---------------- 判断任务是否成功 ---------------------------

        taskSuccessful = true;

        if runUniform && ...
                ~strcmp(uniformStatus, 'success')

            taskSuccessful = false;
        end

        if runTaylorVariance && ...
                ~strcmp(taylorStatus, 'success')

            taskSuccessful = false;
        end

        if runAllSingleFrames

            if singleFailedNum > 0
                taskSuccessful = false;
            end

            if singleSuccessNum ~= selectedFrameNum
                taskSuccessful = false;
            end
        end

        if taskSuccessful

            taskStatus = 'success';

            successTaskNum = ...
                successTaskNum + 1;

            completionText = sprintf( ...
                ['任务完成\n', ...
                 '数据集：%s\n', ...
                 '35层序号：%d\n', ...
                 '物理深度：%+d um\n', ...
                 '原始PSF索引：%d\n', ...
                 '迭代次数：%d\n', ...
