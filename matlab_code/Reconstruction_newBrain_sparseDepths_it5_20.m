                 '成功重建数量：%d\n', ...
                 '完成时间：%s\n'], ...
                datasetName, ...
                layerPosition, ...
                physicalDepth, ...
                originalPSFIndex, ...
                iterNum, ...
                selectedFrameNum, ...
                singleSuccessNum, ...
                char(datetime('now')) ...
            );

            writeTextFile( ...
                completedMarkerPath, ...
                completionText ...
            );

            fprintf( ...
                '\n当前数据集-深度任务全部完成。\n' ...
            );

        else

            taskStatus = 'failed';

            failedTaskNum = ...
                failedTaskNum + 1;

            fprintf(2, ...
                '\n当前数据集-深度任务没有完全成功。\n' ...
            );
        end

        %% ---------------- 写入日志 -----------------------------------

        if isempty(taskMessages)

            taskMessage = '';

        else

            taskMessage = strjoin( ...
                taskMessages, ...
                ' | ' ...
            );
        end

        taskEndTime = datetime('now');

        logCell(end + 1, :) = {
            datasetName, ...
            depthLoop, ...
            layerPosition, ...
            physicalDepth, ...
            originalPSFIndex, ...
            inputFrameNum, ...
            selectedFrameNum, ...
            uniformStatus, ...
            taylorStatus, ...
            singleSuccessNum, ...
            singleFailedNum, ...
            taskStatus, ...
            taskMessage, ...
            saveDepthRoot, ...
            char(taskStartTime), ...
            char(taskEndTime)
        };

        %% ---------------- 保存中间日志 -------------------------------

        saveLogSafely( ...
            logCell, ...
            saveRoot, ...
            logBaseName ...
        );
    end

    %% ---------------- 当前深度完成，清理内存 -------------------------

    clear H_use Ht_use CAindex_use;

    try
        g = gpuDevice;
        reset(g);

        fprintf( ...
            '\n当前深度处理完成，GPU 已 reset。\n' ...
        );

    catch
    end
end

%% ======================== 11. 保存最终日志 ==============================

logPath = saveLogSafely( ...
